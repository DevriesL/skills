#requires -Version 7.0
[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [ValidateSet('exec', 'cd', 'ls', 'read', 'write', 'edit', 'mv', 'grep', 'glob', 'wait', 'init')]
    [string] $Op = 'exec',
    [Parameter(Position = 1)]
    [string] $Target,
    [string] $To,
    [string] $Root = '.',
    [string[]] $Glob,
    [switch] $Literal,
    [switch] $IgnoreCase,
    [AllowEmptyString()][string] $Content,
    [AllowEmptyString()][string] $Old,
    [AllowEmptyString()][string] $New,
    [string] $ExpectedHash,
    [string] $Cwd,
    [string] $TextFile,
    [string] $RequestFile,
    [ValidateRange(1, 1000000000)][int] $From = 1,
    [ValidateRange(1, 10000)][int] $Lines = 120,
    [ValidateRange(1, 1000)][int] $Limit = 100,
    [switch] $All,
    [switch] $Overwrite,
    [switch] $Parents,
    [switch] $Json,
    [switch] $Metrics,
    [string] $Session = 'default',
    [string] $StateRoot = (Join-Path (Get-Location) 'work\wezterm-wsl'),
    [ValidateRange(0, 25)][int] $WaitSeconds = 20,
    [ValidateRange(128, 100000)][int] $MaxChars = 4000,
    [string] $Job
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Op = $Op.ToLowerInvariant()
$helper = Join-Path $PSScriptRoot 'Invoke-WezTerm.ps1'
$StateRoot = [IO.Path]::GetFullPath($StateRoot)

function Quote-PSLiteral([string] $Value) { return "'" + $Value.Replace("'", "''") + "'" }
function Quote-ShellPath([string] $Value) {
    if ($Value -eq '~') { return '"$HOME"' }
    if ($Value.StartsWith('~/')) { return '"$HOME"/' + "'" + $Value.Substring(2).Replace("'", "'\''") + "'" }
    return "'" + $Value.Replace("'", "'\''") + "'"
}

if ($Op -eq 'init') {
    $destination = if ($Target) { [IO.Path]::GetFullPath($Target) } else { Join-Path (Get-Location) 'work\wsl.ps1' }
    if ([IO.File]::Exists($destination) -and -not [IO.File]::ReadAllText($destination).StartsWith('# Generated by wezterm-wsl')) {
        throw "Refusing to overwrite an unrelated launcher: $destination"
    }
    $ownPath = $MyInvocation.MyCommand.Path
    $tokens = $null
    $parseErrors = $null
    $ast = [Management.Automation.Language.Parser]::ParseFile($ownPath, [ref] $tokens, [ref] $parseErrors)
    $forward = @'
if (-not $PSBoundParameters.ContainsKey('StateRoot')) { $PSBoundParameters['StateRoot'] = __STATE__ }
if (-not $PSBoundParameters.ContainsKey('Session')) { $PSBoundParameters['Session'] = __SESSION__ }
& __SCRIPT__ @PSBoundParameters
exit $LASTEXITCODE
'@
    $forward = $forward.Replace('__STATE__', (Quote-PSLiteral $StateRoot)).Replace('__SESSION__', (Quote-PSLiteral $Session)).Replace('__SCRIPT__', (Quote-PSLiteral $ownPath))
    [void] [IO.Directory]::CreateDirectory((Split-Path $destination))
    [IO.File]::WriteAllText($destination, "# Generated by wezterm-wsl; task-local launcher.`n#requires -Version 7.0`n" + $ast.ParamBlock.Extent.Text + "`n" + $forward + "`n", [Text.UTF8Encoding]::new($false))
    Write-Output "launcher=$destination"
    return
}

$arguments = @{ Session = $Session; StateRoot = $StateRoot; WaitSeconds = $WaitSeconds; MaxChars = $MaxChars }
if ($Metrics) { $arguments.Metrics = $true }
if ($Cwd) { $arguments.Cwd = $Cwd }
$temporaryRequest = $null
try {
    if ($RequestFile) {
        if ($Target -or $TextFile -or $PSBoundParameters.ContainsKey('Content')) { throw 'RequestFile cannot be combined with Target, TextFile, or Content.' }
        $arguments.Action = 'Run'
        $arguments.RequestFile = $RequestFile
    }
    elseif ($Op -eq 'wait') {
        $arguments.Action = 'Wait'
        if ($Job -and $Target) { throw 'Supply a job ID either positionally or with -Job.' }
        if ($Job) { $arguments.Job = $Job } elseif ($Target) { $arguments.Job = $Target }
    }
    elseif ($Op -eq 'exec') {
        $arguments.Action = 'Run'
        if ($TextFile) {
            if ($Target) { throw 'Supply command text or TextFile, not both.' }
            $arguments.TextFile = $TextFile
        } else {
            if (-not $Target) { throw 'exec requires a command or TextFile.' }
            $arguments.Text = $Target
        }
    }
    elseif ($Op -eq 'cd') {
        if (-not $Target) { throw 'cd requires a directory.' }
        $arguments.Action = 'Run'
        $arguments.Text = 'builtin cd -- ' + (Quote-ShellPath $Target)
    }
    else {
        if (-not $Target -and $Op -ne 'ls') { throw "$Op requires a path (grep/glob require a pattern)." }
        $request = [ordered]@{ op = $Op; path = $(if ($Target) { $Target } else { '.' }) }
        if ($Op -in @('grep', 'glob')) {
            $request.path = $Root
            $request.pattern = $Target
            $request.limit = $Limit
            $request.max_chars = $MaxChars
            $request.all = [bool] $All
            if ($Glob) { $request.glob = @($Glob) }
            if ($Literal) { $request.literal = $true }
            if ($IgnoreCase) { $request.ignore_case = $true }
        }
        switch ($Op) {
            'ls' { $request.limit = $Limit; $request.max_chars = $MaxChars; $request.all = [bool] $All }
            'read' { $request.from = $From; $request.lines = $Lines; $request.max_chars = $MaxChars }
            'write' {
                if ($TextFile -and $PSBoundParameters.ContainsKey('Content')) { throw 'Supply Content or TextFile, not both.' }
                if ($TextFile) { $request.content = [IO.File]::ReadAllText((Resolve-Path -LiteralPath $TextFile).Path, [Text.Encoding]::UTF8) }
                elseif ($PSBoundParameters.ContainsKey('Content')) { $request.content = $Content }
                else { throw 'write requires Content (which may be empty) or TextFile.' }
            }
            'edit' {
                if (-not $PSBoundParameters.ContainsKey('Old') -or -not $PSBoundParameters.ContainsKey('New')) { throw 'edit requires Old and New (New may be empty).' }
                $request.old = $Old; $request.new = $New; $request.all = [bool] $All
            }
            'mv' { if (-not $To) { throw 'mv requires To, interpreted as an exact destination path.' }; $request.to = $To }
        }
        if ($ExpectedHash) { $request.expected_hash = $ExpectedHash }
        if ($Overwrite) { $request.overwrite = $true }
        if ($Parents) { $request.parents = $true }
        [void] [IO.Directory]::CreateDirectory($StateRoot)
        $temporaryRequest = Join-Path $StateRoot ('.request-' + [guid]::NewGuid().ToString('N') + '.json')
        [IO.File]::WriteAllText($temporaryRequest, ($request | ConvertTo-Json -Depth 8 -Compress), [Text.UTF8Encoding]::new($false))
        $arguments.Action = 'Run'
        $arguments.RequestFile = $temporaryRequest
    }
    $raw = & $helper @arguments
    $result = $raw | ConvertFrom-Json -AsHashtable
}
finally {
    if ($temporaryRequest -and [IO.File]::Exists($temporaryRequest)) { [IO.File]::Delete($temporaryRequest) }
}

$commandExit = if ($result.status -eq 'done') { [int] $result.exit_code } elseif ($result.status -eq 'running') { 0 } else { 1 }
if ($Json) { $result | ConvertTo-Json -Depth 15 -Compress; exit $commandExit }

$header = "[$($result.status)"
if ($result.ContainsKey('exit_code')) { $header += " exit=$($result.exit_code)" }
if ($result.ContainsKey('cwd')) { $header += " cwd=$($result.cwd)" }
if ($result.status -ne 'done') { $header += " job=$($result.job)" }
Write-Output ($header + ']')
if ($result.ContainsKey('result')) {
    $file = $result.result
    if (-not $file.ok) { Write-Output "error $($file.error.code): $($file.error.message)" }
    else {
        switch ($file.op) {
            'read' {
                Write-Output "$($file.path) lines=$($file.total_lines) sha256=$($file.sha256)"
                $number = [int] $file.from
                if ($file.content.Length) {
                    $displayLines = [regex]::Split($file.content, '\r?\n')
                    $lineCount = $displayLines.Length
                    if ($displayLines[-1] -eq '') { $lineCount-- }
                    for ($index = 0; $index -lt $lineCount; $index++) { Write-Output "$number`: $($displayLines[$index])"; $number++ }
                }
                if ($file.truncated) { Write-Output '[truncated; use -From/-Lines or increase -MaxChars]' }
            }
            'ls' {
                Write-Output $file.path
                foreach ($entry in $file.entries) {
                    $suffix = if ($entry.type -eq 'dir') { '/' } elseif ($entry.type -eq 'link') { '@' } else { '' }
                    Write-Output ($entry.name + $suffix)
                }
                if ($file.omitted) { Write-Output "[$($file.omitted) entries omitted; increase -Limit]" }
            }
            { $_ -in @('grep', 'glob') } {
                Write-Output $file.path
                if ($file.op -eq 'grep') {
                    foreach ($match in $file.matches) { Write-Output "$($match.path):$($match.line): $($match.text)" }
                    if (-not $file.matches.Count) { Write-Output '[no matches returned]' }
                } else {
                    foreach ($path in $file.paths) { Write-Output $path }
                    if (-not $file.paths.Count) { Write-Output '[no paths returned]' }
                }
                if ($file.truncated) { Write-Output '[search stopped at limit; narrow the query or increase -Limit/-MaxChars]' }
            }
            'mv' { Write-Output "$($file.path) -> $($file.to)" }
            default {
                Write-Output "$($file.op) $($file.path) bytes=$($file.bytes) sha256=$($file.sha256)"
                if ($file.ContainsKey('replacements')) { Write-Output "replacements=$($file.replacements)" }
            }
        }
    }
}
else {
    if ($result.ContainsKey('stdout')) { Write-Output $result.stdout.TrimEnd("`r", "`n") }
    if ($result.ContainsKey('stderr')) { Write-Output ('[stderr]' + "`n" + $result.stderr.TrimEnd("`r", "`n")) }
}
if ($result.ContainsKey('truncated') -and $result.truncated) { Write-Output "[full output: $($result.full_output_directory)]" }
if ($result.ContainsKey('error')) { Write-Output $result.error }
if ($result.ContainsKey('metrics')) { Write-Output ('metrics=' + ($result.metrics | ConvertTo-Json -Compress)) }
exit $commandExit
